"""Conditional execution: switch tasks, branch labels and task guards.

A *guard* (``when=`` on a task) is a control edge: it orders the guarded task
after its source and decides at runtime whether the task runs. It carries no
data; the guarded task still receives its input through ``depends_on``.
"""

from __future__ import annotations

import enum
import weakref
from abc import abstractmethod
from dataclasses import dataclass
from typing import Any, ClassVar, Generic, Literal, TypeVar, get_args, get_origin

from pydantic import BaseModel, create_model

from taskmaestro.context import ExecutionContext
from taskmaestro.dependencies import OutputRef, OutputReference
from taskmaestro.task import Task, get_output_type

I = TypeVar("I", bound=BaseModel)
L = TypeVar("L")

type GuardOp = Literal["in", "truthy", "falsy", "otherwise"]

#: Output field of a switch task holding the selected branch label.
BRANCH_FIELD = "branch"


class Branch(BaseModel):
    """Output of a :class:`SwitchTask`: the label of the selected branch.

    Every concrete switch task gets its own subclass whose ``branch`` field is
    annotated with the switch's label type.
    """

    branch: Any


def branch_labels(label_type: Any) -> tuple[Any, ...]:
    """Return the labels declared by a switch label type.

    ``bool``, ``Literal[...]`` and :class:`enum.Enum` subclasses are supported.
    """
    if label_type is bool:
        return (True, False)
    if get_origin(label_type) is Literal:
        return get_args(label_type)
    if isinstance(label_type, type) and issubclass(label_type, enum.Enum):
        return tuple(label_type)
    raise TypeError(f"Switch label type must be bool, Literal[...] or an Enum, got {label_type!r}")


def plain_label(value: Any) -> Any:
    """Return a label as plain JSON/YAML data (enum members become their values)."""
    return value.value if isinstance(value, enum.Enum) else value


def _resolve_label_type(cls: type[Any]) -> Any | None:
    """Find the concrete ``L`` of ``SwitchTask[I, L]`` in *cls*'s bases.

    Type variables are substituted through intermediate generic subclasses,
    so ``class Concrete(MySwitch[Literal["a", "b"]])`` resolves its labels
    even when ``MySwitch`` itself is still generic in ``L``.
    """
    label = _label_from_bases(cls, {})
    return None if isinstance(label, TypeVar) else label


def _label_from_bases(cls: type[Any], substitutions: dict[Any, Any]) -> Any | None:
    for base in cls.__dict__.get("__orig_bases__", cls.__bases__):
        origin = get_origin(base) or base
        if not (isinstance(origin, type) and issubclass(origin, SwitchTask)):
            continue
        args = tuple(
            substitutions.get(arg, arg) if isinstance(arg, TypeVar) else arg
            for arg in get_args(base)
        )
        if origin is SwitchTask:
            label = args[1] if len(args) == 2 else None
        else:
            parameters = getattr(origin, "__parameters__", ())
            label = _label_from_bases(origin, dict(zip(parameters, args, strict=False)))
        if label is not None:
            return label
    return None


#: Output models generated by ``SwitchTask.__init_subclass__``. A subclass
#: regenerates these for its own label type but keeps user-defined ones.
_GENERATED_OUTPUTS: weakref.WeakSet[type[BaseModel]] = weakref.WeakSet()


def _defines_own_outputs(cls: type[Any]) -> bool:
    """Return whether *cls* or a base class declares a user-defined ``Outputs``."""
    for klass in cls.__mro__:
        outputs = klass.__dict__.get("Outputs")
        if outputs is not None:
            return outputs not in _GENERATED_OUTPUTS
    return False


class SwitchTask(Task[I, Branch], Generic[I, L]):
    """A task that selects which branch of a workflow runs.

    Subclass ``SwitchTask[InputModel, Literal["a", "b"]]`` (or a ``StrEnum``)
    and implement :meth:`decide`. The task's output is a ``Branch`` model whose
    ``branch`` field holds the returned label. Guard downstream tasks with
    ``handle.on("a")`` or ``handle.otherwise()``.
    """

    #: The labels this switch can select, in declaration order.
    branches: ClassVar[tuple[Any, ...]] = ()

    def __init_subclass__(cls, **kwargs: object) -> None:
        super().__init_subclass__(**kwargs)
        label_type = _resolve_label_type(cls)
        if label_type is None:
            return
        cls.branches = branch_labels(label_type)
        if not _defines_own_outputs(cls):
            outputs = create_model(
                f"{cls.__name__}Branch",
                __base__=Branch,
                __module__=cls.__module__,
                branch=(label_type, ...),
            )
            cls.Outputs = outputs  # type: ignore[attr-defined]
            _GENERATED_OUTPUTS.add(outputs)

    @abstractmethod
    def decide(self, input: I, ctx: ExecutionContext) -> L:
        """Return the label of the branch to run."""
        ...

    def run(self, input: I, ctx: ExecutionContext) -> Branch:
        label = self.decide(input, ctx)
        return get_output_type(type(self)).model_validate({BRANCH_FIELD: label})  # type: ignore[return-value]


class ConditionTask(SwitchTask[I, bool], Generic[I]):
    """A two-way switch: :meth:`decide` returns ``True`` or ``False``.

    Guard downstream tasks with ``handle.if_true()`` and ``handle.if_false()``.
    """

    @abstractmethod
    def decide(self, input: I, ctx: ExecutionContext) -> bool:
        """Return whether the condition holds."""
        ...


class ContextFlagInput(BaseModel):
    """Configuration of a :class:`ContextFlag`: the context service key to read."""

    key: str


class ContextFlag(ConditionTask[ContextFlagInput]):
    """Condition that is ``True`` when the context value under ``key`` is truthy.

    Add it with ``config_fields=["key"]`` and set ``key`` in the job
    configuration. ``Runner.run`` checks that every configured key is
    registered on the execution context before any task runs, including
    flags in nested workflows and in branches that may later be skipped.
    """

    def decide(self, input: ContextFlagInput, ctx: ExecutionContext) -> bool:
        return bool(ctx.resolve(input.key))


def is_switch_task(task_cls: type[Any]) -> bool:
    """Return whether *task_cls* is a concrete switch task."""
    return (
        isinstance(task_cls, type) and issubclass(task_cls, SwitchTask) and bool(task_cls.branches)
    )


@dataclass(frozen=True)
class Condition:
    """An unresolved guard, created by :func:`when` or handle helpers such as ``on()``."""

    source: OutputReference
    op: GuardOp
    values: tuple[Any, ...] = ()


@dataclass(frozen=True)
class Guard:
    """A resolved guard: the referenced output field and the predicate on its value.

    For ``otherwise`` guards, ``values`` holds the switch labels that no other
    guard on the same switch claims; it is filled in during validation.
    """

    ref: OutputRef
    op: GuardOp
    values: tuple[Any, ...] = ()

    def matches(self, value: Any) -> bool:
        """Return whether the guarded task runs for the source *value*.

        ``truthy``/``falsy`` test a ``bool`` value directly; any other value
        counts as truthy when it is set (not ``None``), so ``0``, ``""`` or an
        empty list in an optional field still count as present.
        """
        if self.op == "truthy":
            return _is_set(value)
        if self.op == "falsy":
            return not _is_set(value)
        return value in self.values

    def describe(self) -> str:
        """Return a short human-readable form, used in skip reasons."""
        source = f"{self.ref.task_name}.{self.ref.output_field}"
        if self.op == "truthy":
            return source
        if self.op == "falsy":
            return f"not {source}"
        labels = ", ".join(repr(plain_label(value)) for value in self.values)
        if self.op == "otherwise":
            return f"{source} otherwise ({labels})"
        return f"{source} in [{labels}]"


def _is_set(value: Any) -> bool:
    """Truthiness used by guards: a ``bool`` itself, otherwise ``value is not None``."""
    if isinstance(value, bool):
        return value
    return value is not None


_MISSING: Any = object()


def when(
    source: OutputReference,
    *,
    equals: Any = _MISSING,
    in_: Any = None,
    truthy: bool | None = None,
) -> Condition:
    """Guard a task on an upstream output field.

    Pass exactly one of ``equals=`` (value equality), ``in_=`` (one of several
    values) or ``truthy=`` (``True`` runs the task when the value is ``True``
    or, for non-bool fields, set to anything but ``None``; ``False`` runs it
    otherwise). ``source`` is an output field reference such
    as ``handle.field("kind")`` or ``(task, "kind")``; a switch task may be
    referenced as a whole.
    """
    given = [equals is not _MISSING, in_ is not None, truthy is not None]
    if sum(given) != 1:
        raise TypeError("when() takes exactly one of equals=, in_= or truthy=")
    if equals is not _MISSING:
        return Condition(source, "in", (equals,))
    if in_ is not None:
        if isinstance(in_, str | bytes):
            raise TypeError("when(in_=...) takes a collection of values, not a string")
        values = tuple(in_)
        if not values:
            raise TypeError("when(in_=...) needs at least one value")
        return Condition(source, "in", values)
    return Condition(source, "truthy" if truthy else "falsy")
